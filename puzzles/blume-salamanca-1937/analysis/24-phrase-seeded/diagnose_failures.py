"""Audit whether failed controls retained their base key at the true first width.

Requires the shortlists generated by the control run under out/.
python3 -I diagnose_failures.py > results/failure-diagnostics.json
"""
import hashlib
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
results=[json.loads(l) for l in (HERE / "results/holdout24.jsonl").read_text().splitlines()]
output=[]
for r in results:
    if r["recovered"]:
        continue
    path=HERE / "out" / r["tag"] / "shortlist.json"
    shortlist=json.loads(path.read_text())
    retained=any(s["w1"]==r["plant_w1"] and s["id"]==r["plant_seed_id"] for s in shortlist)
    output.append(dict(distance=r["distance"],trial=r["trial"],tag=r["tag"],
                       base_seed_retained_at_true_w1=retained,
                       shortlist_sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
print(json.dumps(output,indent=1))
