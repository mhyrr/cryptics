"""Rank untouched-data survey candidates from the scores in 0*.md.

Composite = 2*verifier + gap + data_ready + cheapness + payoff (max 30).
Verifier is double-weighted per ideas/pooled-compute.md: compute is cheap,
checking is scarce. ethics_clear < 3 is flagged, not scored.
Run: python3 sources/untouched-data/rank.py > sources/untouched-data/RANKING.md
"""
import re
from pathlib import Path

AXES = ["data_ready", "gap", "verifier", "cheapness", "payoff", "ethics_clear"]
HERE = Path(__file__).parent


def field(sec, name):
    """Text of a '- **Name**' bullet up to the next top-level '- **' bullet."""
    m = re.search(r"^- \*\*%s[^\n]*?(?:\*\*)?[:.]?\*?\*?(.*?)(?=^- \*\*|\Z)" % name, sec, re.S | re.M)
    return re.sub(r"\s+", " ", m.group(1)).strip(" :.*") if m else ""


def load():
    rows = []
    for f in sorted(HERE.glob("0*.md")):
        for sec in re.split(r"\n(?=### )", f.read_text()):
            m = re.match(r"### (?:(\d+)\.\s*)?(.+)", sec)
            if not m or not m.group(1):
                continue
            s = {}
            for ax in AXES:
                mm = re.search(r"`?%s`?\s*(\d)" % ax, sec)
                if mm:
                    s[ax] = int(mm.group(1))
            if len(s) < 6:
                continue
            crowd = re.search(r"\b(OPEN|PARTLY|CROWDED)\b", sec)
            rows.append(dict(
                composite=2 * s["verifier"] + s["gap"] + s["data_ready"] + s["cheapness"] + s["payoff"],
                file=f.name, ref=f"{f.name[:2]}#{m.group(1)}",
                title=re.sub(r"\s+", " ", m.group(2)).strip(), scores=s,
                crowding=crowd.group(1) if crowd else "?",
                data=field(sec, "Data"), verifier=field(sec, "Verifier"),
                recipe=field(sec, "Recipe"), section=sec))
    rows.sort(key=lambda r: (-r["composite"], -r["scores"]["payoff"]))
    return rows


if __name__ == "__main__":
    rows = load()
    print("# Untouched-data candidates, ranked\n")
    print("*Generated by `sources/untouched-data/rank.py`; do not hand-edit. Per-candidate worksheet: `CANDIDATES.md`.*")
    print("Composite = 2×verifier + gap + data_ready + cheapness + payoff (max 30). "
          "⚠ = ethics_clear < 3. Crowding is the first OPEN/PARTLY/CROWDED word in the section.\n")
    print("| # | Composite | File | Candidate | data | gap | verif | cheap | payoff | ethics | crowding |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(rows, 1):
        s = r["scores"]
        flag = " ⚠" if s["ethics_clear"] < 3 else ""
        print(f"| {i} | {r['composite']} | {r['ref']} | {r['title'][:90]}{flag} | {s['data_ready']} | {s['gap']} | "
              f"{s['verifier']} | {s['cheapness']} | {s['payoff']} | {s['ethics_clear']} | {r['crowding']} |")
    print(f"\n{len(rows)} candidates parsed.")
