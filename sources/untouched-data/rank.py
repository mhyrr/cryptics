"""Rank untouched-data survey candidates from the scores in 0*.md.

Composite = 2*verifier + gap + data_ready + cheapness + payoff (max 30).
Verifier is double-weighted per ideas/pooled-compute.md: compute is cheap,
checking is scarce. ethics_clear < 3 is flagged, not scored.
Run: python3 sources/untouched-data/rank.py > sources/untouched-data/RANKING.md
"""
import re, sys
from pathlib import Path

AXES = ["data_ready", "gap", "verifier", "cheapness", "payoff", "ethics_clear"]
here = Path(__file__).parent
rows = []
for f in sorted(here.glob("0*.md")):
    text = f.read_text()
    for sec in re.split(r"\n(?=### )", text):
        m = re.match(r"### (?:(\d+)\.\s*)?(.+)", sec)
        if not m or not m.group(1):
            continue
        s = {}
        for ax in AXES:
            mm = re.search(r"`?%s`?\s*(\d)" % ax, sec)
            if mm:
                s[ax] = int(mm.group(1))
        if len(s) < 6:
            continue
        crowd = re.search(r"\b(OPEN|PARTLY|CROWDED)\b", sec)
        comp = 2 * s["verifier"] + s["gap"] + s["data_ready"] + s["cheapness"] + s["payoff"]
        title = re.sub(r"\s+", " ", m.group(2)).strip()
        rows.append((comp, f.name[:2], m.group(1), title, s, crowd.group(1) if crowd else "?"))

rows.sort(key=lambda r: (-r[0], -r[4]["payoff"]))
print("# Untouched-data candidates, ranked\n")
print("*Generated by `sources/untouched-data/rank.py`; do not hand-edit.*")
print("Composite = 2×verifier + gap + data_ready + cheapness + payoff (max 30). "
      "⚠ = ethics_clear < 3. Crowding is the first OPEN/PARTLY/CROWDED word in the section.\n")
print("| # | Composite | File | Candidate | data | gap | verif | cheap | payoff | ethics | crowding |")
print("|---|---|---|---|---|---|---|---|---|---|---|")
for i, (c, fid, n, t, s, cr) in enumerate(rows, 1):
    flag = " ⚠" if s["ethics_clear"] < 3 else ""
    print(f"| {i} | {c} | {fid}#{n} | {t[:90]}{flag} | {s['data_ready']} | {s['gap']} | "
          f"{s['verifier']} | {s['cheapness']} | {s['payoff']} | {s['ethics_clear']} | {cr} |")
print(f"\n{len(rows)} candidates parsed.")
