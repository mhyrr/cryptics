"""Write CANDIDATES.md: one worksheet block per candidate, in RANKING.md order.

For each candidate: scores, crowding, data URLs (from its **Data** and **Recipe** fields, plus Sources lines tagged PRIMARY), whether
each data host answered from the machine running this script, the verifier and
the first recipe step. Reachability is probed live (curl, 12 s, any HTTP status
counts as reachable; connection refused/proxy-denied/DNS failure does not).
Run: python3 sources/untouched-data/candidates.py > sources/untouched-data/CANDIDATES.md
Use --no-probe to skip network checks.
"""
import datetime, re, subprocess, sys
from urllib.parse import urlparse
import rank

URL = re.compile(r"(?:https?|s3|gs)://[^\s)>\]`'\",|*]+")


def links(r):
    """Data links from the Data and Recipe fields; s3:// and gs:// mapped to their public HTTPS endpoints."""
    out = []
    m = re.search(r"^- \*\*Sources.*?(?=^- \*\*|^##|\Z)", r["section"], re.S | re.M)
    primary = " ".join(l for l in (m.group(0).splitlines() if m else []) if "PRIMARY" in l)
    for u in URL.findall(r["data"] + " " + r["recipe"] + " " + primary):
        u = u.rstrip(".;:")
        if u.startswith("s3://"):
            b, _, k = u[5:].partition("/"); u = f"https://{b}.s3.amazonaws.com/{k}"
        elif u.startswith("gs://"):
            u = "https://storage.googleapis.com/" + u[5:]
        out.append(u)
    return list(dict.fromkeys(out))


def probe(host):
    r = subprocess.run(["curl", "-s", "-o", "/dev/null", "-m", "12", "-w", "%{http_code}", f"https://{host}/"],
                       capture_output=True, text=True)
    return r.stdout.strip() not in ("", "000")


def clip(t, n):
    return t if len(t) <= n else t[: n].rsplit(" ", 1)[0] + " …"


rows = rank.load()
do_probe = "--no-probe" not in sys.argv
hosts = sorted({urlparse(u).hostname for r in rows for u in links(r)} - {None})
reach = {h: probe(h) for h in hosts} if do_probe else {}
today = datetime.date.today().isoformat()

print("# Untouched-data candidates — worksheet\n")
print(f"*Generated by `sources/untouched-data/candidates.py` on {today}; do not hand-edit "
      "(add triage notes in a separate file or in the survey file). Order and scores as in `RANKING.md`. "
      "Full detail, precedent, traps and sources are in the survey file named on each block.*\n")
if do_probe:
    ok = sum(reach.values())
    print(f"**Reachability** is from the Claude Code cloud container on {today}: {ok} of {len(hosts)} data hosts "
          "answered. ✅ = host answered here, ⛔ = refused (network policy or DNS). ⛔ only means "
          "\"pull it down elsewhere\"; it says nothing about whether the data is public.\n")
print("Legend: scores are data_ready / gap / verifier / cheapness / payoff / ethics_clear (1–5). "
      "⚠ = ethics_clear < 3: read the Ethics field before touching it.\n")
print("## Index\n")
print("| # | Comp | Candidate | Crowding | Data reachable here |")
print("|---|---|---|---|---|")
for i, r in enumerate(rows, 1):
    hs = sorted({urlparse(u).hostname for u in links(r)} - {None})
    rs = "—" if not hs else ("all ✅" if all(reach.get(h) for h in hs) else
                             "none ⛔" if not any(reach.get(h) for h in hs) else "some ✅")
    warn = " ⚠" if r["scores"]["ethics_clear"] < 3 else ""
    print(f"| {i} | {r['composite']} | [{clip(r['title'], 80)}](#c{i}){warn} | {r['crowding']} | {rs if do_probe else '?'} |")
print()
for i, r in enumerate(rows, 1):
    s = r["scores"]
    print(f'<a id="c{i}"></a>\n### {i}. {r["title"]}\n')
    print(f"- **Survey file:** [`{r['file']}`]({r['file']}) candidate {r['ref'].split('#')[1]}")
    print(f"- **Composite {r['composite']}** · scores {s['data_ready']}/{s['gap']}/{s['verifier']}/"
          f"{s['cheapness']}/{s['payoff']}/{s['ethics_clear']} · crowding **{r['crowding']}**"
          + (" · ⚠ ethics" if s["ethics_clear"] < 3 else ""))
    urls = links(r)
    if urls:
        print(f"- **Data:** {clip(r['data'], 220)}")
        print("- **Data links:**")
        for u in urls[:10]:
            h = urlparse(u).hostname
            mark = (" ✅" if reach.get(h) else " ⛔") if do_probe else ""
            print(f"  - {u}{mark}")
    else:
        print(f"- **Data:** {clip(r['data'], 300) or '(see survey file)'}")
    print(f"- **Verifier:** {clip(r['verifier'], 350) or '(see survey file)'}")
    print(f"- **First steps:** {clip(r['recipe'], 350) or '(see survey file)'}")
    print("- **Triage:** [ ] look at · [ ] pull data · [ ] pilot · [ ] drop\n")
